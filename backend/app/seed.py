def hash_password(plain: str) -> str:
    return bcrypt.hashpw(plain.encode("utf-8"), bcrypt.gensalt()).decode("utf-8")


def _status(total: int, available: int, archived: bool = False) -> str:
    if archived:
        return "archived"
    if available <= 0:
        return "unavailable"
    if available < total:
        return "partially_available"
    return "available"


